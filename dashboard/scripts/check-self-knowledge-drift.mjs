#!/usr/bin/env node
// === JARVIS MOD #91 — self-knowledge drift checker ===
//
// Regenerates the self-knowledge doc to a temp file and diffs it against the
// committed one. Exit 0 = in sync, exit 1 = drifted (with the differing lines
// printed), exit 2 = the checker itself could not run.
//
// A generated doc nobody verifies is just a doc, with the same decay as prose.
// This is the thing that makes the guarantee real.
//
// NORMALIZATION: the source-revision line is stripped from both sides before
// comparing. Without that, every unrelated commit would move HEAD and report
// drift, the check would cry wolf on day one, and someone would delete it.
// Every other line is compared exactly.
//
// NOT wired into a git hook or CI on purpose — hooks affect every committer,
// which is Scott's decision, not this script's.
// === END header ===

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const DASHBOARD = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GENERATOR = path.join(DASHBOARD, 'scripts', 'generate-self-knowledge.mjs');

/** Both generated artifacts are checked; llms.txt points at the other one, and a
 *  pointer to a file that no longer describes reality is worse than no pointer. */
const ARTIFACTS = [
  { name: 'public/jarvis-self-knowledge.md', out: 'SELF_KNOWLEDGE_OUT' },
  { name: 'public/llms.txt', out: 'LLMS_TXT_OUT' },
];

/** Drop the one line that legitimately moves on every commit. */
const normalize = (text) =>
  text
    .split('\n')
    .filter((line) => !line.startsWith('Generated by `dashboard/scripts/generate-self-knowledge.mjs`'))
    .join('\n');

for (const a of ARTIFACTS) {
  if (!fs.existsSync(path.join(DASHBOARD, a.name))) {
    console.error(`FAIL: ${a.name} does not exist. Run: npm run self-knowledge`);
    process.exit(1);
  }
}

// One generator run produces both artifacts, so run it once into a temp dir.
const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'selfknow-'));
const env = { ...process.env };
for (const a of ARTIFACTS) env[a.out] = path.join(tmpDir, path.basename(a.name));

try {
  execFileSync(process.execPath, [GENERATOR], { cwd: DASHBOARD, env, stdio: 'pipe' });
} catch (err) {
  console.error(`FAIL: the generator did not run.\n${err.stderr?.toString() || err.message}`);
  process.exit(2);
}

let drifted = false;
for (const a of ARTIFACTS) {
  const expected = normalize(fs.readFileSync(env[a.out], 'utf8')).split('\n');
  const actual = normalize(fs.readFileSync(path.join(DASHBOARD, a.name), 'utf8')).split('\n');

  const diffs = [];
  for (let i = 0; i < Math.max(expected.length, actual.length); i++) {
    if (expected[i] !== actual[i]) {
      diffs.push({ line: i + 1, committed: actual[i], regenerated: expected[i] });
    }
  }

  if (diffs.length === 0) {
    console.log(`OK: ${a.name} matches the code.`);
    continue;
  }
  drifted = true;
  console.error(
    `\nDRIFT: ${a.name} is ${diffs.length} line(s) out of date with the code.\n` +
      'The code changed and the doc did not. Fix with: npm run self-knowledge\n',
  );
  // Cap the output — a section that moved shifts every line after it, and a
  // thousand-line dump buries the first real difference, which is the useful one.
  for (const d of diffs.slice(0, 15)) {
    console.error(`  line ${d.line}`);
    console.error(`    committed:   ${d.committed ?? '(missing)'}`);
    console.error(`    regenerated: ${d.regenerated ?? '(missing)'}`);
  }
  if (diffs.length > 15) console.error(`  … and ${diffs.length - 15} more.`);
}

process.exit(drifted ? 1 : 0);
